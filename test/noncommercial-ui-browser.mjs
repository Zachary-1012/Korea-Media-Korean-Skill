import {createServer} from "node:http";
import {readFile,mkdir} from "node:fs/promises";
import {resolve,dirname,extname,sep,join} from "node:path";
import {fileURLToPath} from "node:url";
import {chromium} from "playwright-core";
import assert from "node:assert/strict";
const root=resolve(dirname(fileURLToPath(import.meta.url)),".."),PORT=8896;
const report={checks:[],errors:[],at:new Date().toISOString(),pass:false};
const server=createServer(async(req,res)=>{
 try{
  const pathname=decodeURIComponent(new URL(req.url,"http://localhost").pathname).replace(/^\/+/,"")||"index.html";
  const path=resolve(root,pathname);
  if(!path.startsWith(root+sep))throw Error("outside project");
  const data=await readFile(path);const types={".html":"text/html",".css":"text/css",".js":"text/javascript",".mjs":"text/javascript",".json":"application/json"};
  res.writeHead(200,{"content-type":types[extname(path)]||"application/octet-stream","cache-control":"no-store"}).end(data);
 }catch(e){res.writeHead(404).end(String(e));}
});
await new Promise(r=>server.listen(PORT,"127.0.0.1",r));
let browser;
const hard=setTimeout(()=>{console.error("NONCOMMERCIAL_BROWSER_HARD_TIMEOUT");process.exit(124)},170000);hard.unref();
try{
 browser=await chromium.launch({headless:true,channel:"msedge",args:["--disable-extensions"]});
 const context=await browser.newContext({viewport:{width:1340,height:900}});
 const page=await context.newPage();page.setDefaultTimeout(20000);
 page.on("pageerror",e=>report.errors.push(e.message));
 const go=url=>page.goto("http://127.0.0.1:"+PORT+"/#/"+url,{waitUntil:"commit",timeout:30000});
 await go("wordbank");await page.locator("#expanded-vocabulary .kw-list").waitFor();
 assert.match(await page.locator("#expanded-vocabulary h1").innerText(),/认识更多词/);
 assert.match(await page.locator(".kw-stats").innerText(),/4704/);
 await page.screenshot({path:join(root,"test-results","wordbank-desktop.png")});
 report.checks.push("licensed 4704-word dataset visible in browser");
 await page.locator("#kw-search").fill("사랑");
 await page.waitForTimeout(300);
 console.log("VOCAB_QUERY_RENDERED",await page.locator(".kw-word").count());
 assert.ok((await page.locator(".kw-word").count())>=1);
 await page.locator('[data-kw-save="사랑"]').click();
 assert.match(await page.locator(".kw-stats").innerText(),/1/);
 await page.locator('[data-kw="study"]').click();
 await page.locator("#kw-answer").fill("사랑");
 await page.locator('[data-kw="check"]').click();
 assert.match(await page.locator(".kw-feedback").innerText(),/字面回忆正确/);
 await page.locator('[data-kw="next-card"]').click();
 await page.locator('[data-kw="back"]').click();
 await page.reload({waitUntil:"commit",timeout:30000});
 await page.locator("#expanded-vocabulary .kw-list").waitFor();
 assert.ok(await page.evaluate(()=>Boolean(JSON.parse(localStorage.getItem("kmsExtendedVocabularyV1")).saved["사랑"])));
 report.checks.push("search -> saved vocabulary -> typed recall -> spaced retention -> local persistence");
 await page.locator('.v3-side-nav [data-v3-nav="culture"]').click();
 await page.locator("#korean-culture .ks-case-list").waitFor();
 assert.equal(await page.locator("[data-case]").count(),18);
 await page.screenshot({path:join(root,"test-results","culture-desktop.png")});
 await page.locator('[data-case="E01"]').click();
 await page.locator('[data-culture-choice="good"]').click();
 assert.match(await page.locator(".ks-feedback").innerText(),/情境/);
 await page.locator("#ks-my-answer").fill("안녕하세요. 처음 뵙겠습니다.");
 await page.locator('[data-culture="save-practice"]').click();
 assert.ok(await page.evaluate(()=>Boolean(JSON.parse(localStorage.getItem("kmsKoreanEtiquetteV1")).E01.practice)));
 report.checks.push("etiquette lesson -> suitable speech choice -> explanation -> independent Korean reply saved");
 await page.locator('[data-culture="back"]').click();
 assert.match(await page.locator('[data-case="E01"]').innerText(),/已练过/);
 await context.close();
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const mp=await mobile.newPage();
 mp.on("pageerror",e=>report.errors.push("mobile: "+e.message));
 await mp.goto("http://127.0.0.1:"+PORT+"/#/wordbank",{waitUntil:"commit",timeout:30000});
 await mp.locator("#expanded-vocabulary .kw-list").waitFor();
 const w=await mp.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(w.scroll<=w.client+2,"wordbank horizontal overflow "+JSON.stringify(w));
 await mp.screenshot({path:join(root,"test-results","wordbank-mobile.png")});
 await mp.goto("http://127.0.0.1:"+PORT+"/#/culture",{waitUntil:"commit",timeout:30000});
 await mp.locator("#korean-culture .ks-case-list").waitFor();
 const c=await mp.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(c.scroll<=c.client+2,"culture horizontal overflow "+JSON.stringify(c));
 await mp.screenshot({path:join(root,"test-results","culture-mobile.png")});
 await mobile.close();
 report.checks.push("390px mobile bilingual wordbank and etiquette no horizontal overflow");
 assert.deepEqual(report.errors,[]);
 report.pass=true;
 console.log("NONCOMMERCIAL_UI_BROWSER",JSON.stringify(report,null,2));
}catch(e){report.errors.push(e.stack||String(e));console.error("NONCOMMERCIAL_UI_FAILED",JSON.stringify(report,null,2));process.exitCode=1;}
finally{if(browser)await browser.close();await new Promise(r=>server.close(r));}
